using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace ParquetNeo.Generator
{
    /// <summary>Writes the code that registers the mappings of a set of types when the assembly is loaded, and the code each needs.</summary>
    internal sealed class MappingWriter
    {
        private const string Generated = "global::ParquetNeo.Serialization.Generated";

        private readonly StringBuilder _code = new StringBuilder();
        private readonly List<ObjectModel> _objects;
        private readonly Dictionary<string, int> _numbers;
        private readonly List<string> _enums;

        private MappingWriter(List<ObjectModel> objects)
        {
            _objects = objects;
            _numbers = new Dictionary<string, int>();
            for (int i = 0; i < objects.Count; i++)
            {
                _numbers.Add(objects[i].Type, i);
            }

            _enums = objects.SelectMany(o => o.Properties).SelectMany(p => Enums(p.Shape)).Distinct().OrderBy(e => e).ToList();
        }

        /// <param name="roots">The row types to register, by their object model.</param>
        /// <param name="objects">Every object type any of them is made of, each once.</param>
        public static string Write(IReadOnlyList<ObjectModel> roots, IReadOnlyList<ObjectModel> objects) =>
            new MappingWriter(objects.OrderBy(o => o.Type, System.StringComparer.Ordinal).ToList()).Write(roots);

        private string Write(IReadOnlyList<ObjectModel> roots)
        {
            Line("// <auto-generated>ParquetNeo.Generator</auto-generated>");
            Line("#nullable disable");
            Line("#pragma warning disable CA2255 // The mappings are registered when the assembly is loaded, which is what a module initializer is for.");
            Line();
            Line("namespace ParquetNeo.Generated");
            Line("{");
            Line("    internal static class ParquetNeoMappings");
            Line("    {");
            Line("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            Line("        internal static void Register()");
            Line("        {");
            foreach (var root in roots.OrderBy(r => r.Type, System.StringComparer.Ordinal))
            {
                int number = _numbers[root.Type];
                Line($"            {Generated}.MappingRegistry.RegisterWrite<{root.Type}>(CreateWrite{number});");
                if (root.ReadProblem == null)
                {
                    Line($"            {Generated}.MappingRegistry.RegisterRead<{root.Type}>(CreateRead{number});");
                }
            }

            Line("        }");
            foreach (var root in roots)
            {
                WriteCreate(root);
            }

            for (int i = 0; i < _objects.Count; i++)
            {
                WriteObject(_objects[i], i);
            }

            Line("    }");
            Line("}");
            return _code.ToString();
        }

        private void WriteCreate(ObjectModel root)
        {
            int number = _numbers[root.Type];
            Line();
            Line($"        private static {Generated}.WriteMapping<{root.Type}> CreateWrite{number}()");
            Line("        {");
            WriteEnums("            ");
            Line($"            var builder = new {Generated}.WriteMappingBuilder<{root.Type}>(Shred{number});");
            Line($"            Properties{number}(builder);");
            Line("            return builder.Build();");
            Line("        }");
            if (root.ReadProblem != null)
            {
                return;
            }

            Line();
            Line($"        private static {Generated}.ReadMapping<{root.Type}> CreateRead{number}()");
            Line("        {");
            WriteEnums("            ");
            Line($"            var builder = new {Generated}.ReadMappingBuilder<{root.Type}>(Assemble{number});");
            Line($"            ReadProperties{number}(builder);");
            Line("            return builder.Build();");
            Line("        }");
        }

        private void WriteObject(ObjectModel model, int number)
        {
            string builder = $"{Generated}.WriteMappingBuilder<TRow>";
            Line();
            Line($"        private static void Describe{number}<TRow>({builder} builder, string name, string description, bool optional)");
            Line("        {");
            Line($"            builder.BeginObject<{model.Type}>(name, description, optional, Shred{number});");
            Line($"            Properties{number}(builder);");
            Line("            builder.End();");
            Line("        }");
            Line();
            Line($"        private static void Properties{number}<TRow>({builder} builder)");
            Line("        {");
            foreach (var property in model.Properties)
            {
                WriteDescription(property.Shape, Literal(property.Name), Literal(property.Description), "            ", "builder", write: true);
            }

            Line("        }");
            Line();
            Line($"        private static void Shred{number}({model.Type} row, {Generated}.RowSink sink)");
            Line("        {");
            int column = 0;
            for (int p = 0; p < model.Properties.Count; p++)
            {
                var property = model.Properties[p];
                WriteShred(property, p, column);
                column += property.Shape.WriteColumns;
            }

            Line("        }");
            if (model.ReadProblem == null)
            {
                WriteReadObject(model, number);
            }
        }

        private void WriteReadObject(ObjectModel model, int number)
        {
            string builder = $"{Generated}.ReadMappingBuilder<TRow>";
            var readable = model.Properties.Where(p => p.Read).ToList();
            Line();
            Line($"        private static void DescribeRead{number}<TRow>({builder} builder, string name, string description, bool optional)");
            Line("        {");
            Line($"            builder.BeginObject<{model.Type}>(name, description, optional, Assemble{number});");
            Line($"            ReadProperties{number}(builder);");
            Line("            builder.End();");
            Line("        }");
            Line();
            Line($"        private static void ReadProperties{number}<TRow>({builder} builder)");
            Line("        {");
            foreach (var property in readable)
            {
                WriteDescription(property.Shape, Literal(property.Name), Literal(property.Description), "            ", "builder", write: false);
            }

            Line("        }");
            Line();
            WriteAssemble(model, number, readable);
        }

        /// <summary>The method that creates an object from what its properties read: through the constructor, when there is one with parameters, and then the setters of the rest.</summary>
        private void WriteAssemble(ObjectModel model, int number, List<PropertyModel> readable)
        {
            var expressions = new List<string>();
            int column = 0;
            for (int p = 0; p < readable.Count; p++)
            {
                expressions.Add(ReadExpression(readable[p].Shape, p, column));
                column += readable[p].Shape.ReadColumns;
            }

            var arguments = readable
                .Select((property, index) => (property.Parameter, Expression: expressions[index]))
                .Where(a => a.Parameter >= 0)
                .OrderBy(a => a.Parameter)
                .Select(a => a.Expression)
                .ToList();
            string call = model.UsesConstructor ? $"new {model.Type}({string.Join(", ", arguments)})" : $"new {model.Type}";
            Line($"        private static {model.Type} Assemble{number}({Generated}.RowSource source) => {call}");
            var setters = readable.Select((property, index) => (Property: property, Expression: expressions[index])).Where(a => a.Property.Parameter < 0).ToList();
            if (setters.Count == 0)
            {
                Line("        ;");
                return;
            }

            Line("        {");
            foreach (var (property, expression) in setters)
            {
                Line($"            {property.PropertyName} = {expression},");
            }

            Line("        };");
        }

        /// <summary>The calls that describe a property, an element, a key or a value, and what is inside it.</summary>
        private void WriteDescription(ShapeModel shape, string name, string description, string indent, string builder, bool write)
        {
            string optional = shape.Optional ? "true" : "false";
            switch (shape.Kind)
            {
                case ShapeKind.Leaf:
                    string options = write ? LeafOptions(shape) : "";
                    Line($"{indent}{builder}.Leaf<{shape.Type}>({name}, {description}, optional: {optional}{options});");
                    break;
                case ShapeKind.Object:
                    Line($"{indent}{(write ? "Describe" : "DescribeRead")}{_numbers[shape.Type]}({builder}, {name}, {description}, optional: {optional});");
                    break;
                case ShapeKind.List:
                    WriteList(shape, name, description, indent, builder, write);
                    break;
                default:
                    WriteMap(shape, name, description, indent, builder, write);
                    break;
            }
        }

        private void WriteList(ShapeModel shape, string name, string description, string indent, string builder, bool write)
        {
            var element = shape.Element!;
            string optional = shape.Optional ? "true" : "false";
            string method = element.IsNullableValue ? "BeginNullableList" : "BeginList";
            string arguments = write ? "" : $", elementOptional: {Bool(element.Optional)}{Create(shape)}";
            Line($"{indent}{builder}.{method}<{shape.Type}, {element.Type}>({name}, {description}, optional: {optional}{arguments});");
            WriteDescription(element, "null", "null", indent, builder, write);
            Line($"{indent}{builder}.End();");
        }

        private void WriteMap(ShapeModel shape, string name, string description, string indent, string builder, bool write)
        {
            var value = shape.Element!;
            string optional = shape.Optional ? "true" : "false";
            string method = value.IsNullableValue ? "BeginMapOfNullable" : "BeginMap";
            string arguments = write ? "" : $", valueOptional: {Bool(value.Optional)}, create: {shape.Create}";
            Line($"{indent}{builder}.{method}<{shape.Type}, {shape.Key!.Type}, {value.Type}>({name}, {description}, optional: {optional}{arguments});");
            WriteDescription(shape.Key, "null", "null", indent, builder, write);
            WriteDescription(value, "null", "null", indent, builder, write);
            Line($"{indent}{builder}.End();");
        }

        private static string LeafOptions(ShapeModel shape)
        {
            string options = shape.Settings == null ? "" : $", settings: {shape.Settings}";
            options += shape.Encoding == null ? "" : $", encoding: {shape.Encoding}";
            options += shape.Dictionary == null ? "" : $", dictionary: {shape.Dictionary}";
            return options;
        }

        private static string Create(ShapeModel shape) => shape.Create == null ? "" : $", create: {shape.Create}";

        private static string Bool(bool value) => value ? "true" : "false";

        private void WriteShred(PropertyModel property, int index, int column)
        {
            var shape = property.Shape;
            string read = $"row.{property.PropertyName}";
            if (shape.Kind == ShapeKind.Leaf)
            {
                if (shape.Optional)
                {
                    Line($"            if ({read} is {{ }} value{index}) {{ sink.Present({column}, value{index}); }} else {{ sink.Missing({column}); }}");
                }
                else
                {
                    Line($"            sink.Required({column}, {read});");
                }

                return;
            }

            if (shape.IsNullableValue)
            {
                Line($"            sink.Child<{shape.Type}>({index}, {read}.GetValueOrDefault(), {read}.HasValue);");
            }
            else if (shape.IsValueType)
            {
                Line($"            sink.Child<{shape.Type}>({index}, {read}, true);");
            }
            else
            {
                Line($"            sink.Child<{shape.Type}>({index}, {read}, {read} != null);");
            }
        }

        private static string ReadExpression(ShapeModel shape, int index, int column)
        {
            string wrapped = shape.IsNullableValue ? $"({shape.Type}?)value{index}" : $"value{index}";
            if (shape.Kind == ShapeKind.Leaf)
            {
                return shape.Optional
                    ? $"source.TryTake<{shape.Type}>({column}, out var value{index}) ? {wrapped} : null"
                    : $"source.Take<{shape.Type}>({column})";
            }

            return shape.Optional
                ? $"source.TryReadChild<{shape.Type}>({index}, out var value{index}) ? {wrapped} : null"
                : $"source.ReadChild<{shape.Type}>({index})";
        }

        private void WriteEnums(string indent)
        {
            foreach (string type in _enums)
            {
                Line($"{indent}global::ParquetNeo.ColumnTypes.ColumnTypeRegistry.RegisterEnum<{type}>();");
            }
        }

        private static IEnumerable<string> Enums(ShapeModel shape)
        {
            if (shape.Kind == ShapeKind.Leaf)
            {
                return shape.IsEnum ? new[] { shape.Type } : Enumerable.Empty<string>();
            }

            var inner = new List<string>();
            foreach (var child in new[] { shape.Element, shape.Key }.Where(child => child != null))
            {
                inner.AddRange(Enums(child!));
            }

            return inner;
        }

        private void Line(string text = "") => _code.AppendLine(text);

        private static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, quote: true);
    }
}
