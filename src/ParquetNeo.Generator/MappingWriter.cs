using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace ParquetNeo.Generator
{
    /// <summary>Writes the code that registers the mappings of a set of types when the assembly is loaded.</summary>
    internal static class MappingWriter
    {
        private const string Generated = "global::ParquetNeo.Serialization.Generated";

        public static string Write(IReadOnlyList<MappingModel> models)
        {
            var code = new StringBuilder();
            code.AppendLine("// <auto-generated>ParquetNeo.Generator</auto-generated>");
            code.AppendLine("#nullable enable");
            code.AppendLine("#pragma warning disable CA2255 // The mappings are registered when the assembly is loaded, which is what a module initializer is for.");
            code.AppendLine();
            code.AppendLine("namespace ParquetNeo.Generated");
            code.AppendLine("{");
            code.AppendLine("    internal static class ParquetNeoMappings");
            code.AppendLine("    {");
            code.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            code.AppendLine("        internal static void Register()");
            code.AppendLine("        {");
            for (int i = 0; i < models.Count; i++)
            {
                code.AppendLine($"            {Generated}.MappingRegistry.RegisterWrite<{models[i].TypeName}>(CreateWrite{i});");
                if (models[i].ReadColumns.Count > 0)
                {
                    code.AppendLine($"            {Generated}.MappingRegistry.RegisterRead<{models[i].TypeName}>(CreateRead{i});");
                }
            }

            code.AppendLine("        }");
            for (int i = 0; i < models.Count; i++)
            {
                WriteCreateWrite(code, models[i], i);
                if (models[i].ReadColumns.Count > 0)
                {
                    WriteCreateRead(code, models[i], i);
                }
            }

            code.AppendLine("    }");
            code.AppendLine("}");
            return code.ToString();
        }

        private static void WriteCreateWrite(StringBuilder code, MappingModel model, int number)
        {
            code.AppendLine();
            code.AppendLine($"        private static {Generated}.WriteMapping<{model.TypeName}> CreateWrite{number}()");
            code.AppendLine("        {");
            WriteEnums(code, model.WriteColumns);
            code.AppendLine($"            return new {Generated}.WriteMappingBuilder<{model.TypeName}>()");
            foreach (var column in model.WriteColumns)
            {
                string options = string.Concat(
                    column.Settings is null ? "" : $", settings: {column.Settings}",
                    column.Encoding is null ? "" : $", encoding: {column.Encoding}",
                    column.Dictionary is null ? "" : $", dictionary: {column.Dictionary}");
                code.AppendLine($"                .Column<{column.ValueType}>({Literal(column.Name)}, {Literal(column.Description)}, optional: {Bool(column.Optional)}{options})");
            }

            code.AppendLine("                .Build(static (row, sink) =>");
            code.AppendLine("                {");
            for (int i = 0; i < model.WriteColumns.Count; i++)
            {
                var column = model.WriteColumns[i];
                if (column.Optional)
                {
                    code.AppendLine($"                    if (row.{column.PropertyName} is {{ }} value{i})");
                    code.AppendLine($"                    {{ sink.Present({i}, value{i}); }}");
                    code.AppendLine("                    else");
                    code.AppendLine($"                    {{ sink.Missing({i}); }}");
                }
                else
                {
                    code.AppendLine($"                    sink.Required({i}, row.{column.PropertyName});");
                }
            }

            code.AppendLine("                });");
            code.AppendLine("        }");
        }

        private static void WriteCreateRead(StringBuilder code, MappingModel model, int number)
        {
            code.AppendLine();
            code.AppendLine($"        private static {Generated}.ReadMapping<{model.TypeName}> CreateRead{number}()");
            code.AppendLine("        {");
            WriteEnums(code, model.ReadColumns);
            code.AppendLine($"            return new {Generated}.ReadMappingBuilder<{model.TypeName}>()");
            foreach (var column in model.ReadColumns)
            {
                code.AppendLine($"                .Column<{column.ValueType}>({Literal(column.Name)}, {Literal(column.Description)}, optional: {Bool(column.Optional)})");
            }

            code.AppendLine("                .Build(static source => new " + model.TypeName);
            code.AppendLine("                {");
            for (int i = 0; i < model.ReadColumns.Count; i++)
            {
                var column = model.ReadColumns[i];
                string value = column.Optional
                    ? $"source.TryTake<{column.ValueType}>({i}, out var value{i}) ? ({column.ValueType}?)value{i} : null"
                    : $"source.Take<{column.ValueType}>({i})";
                code.AppendLine($"                    {column.PropertyName} = {value},");
            }

            code.AppendLine("                });");
            code.AppendLine("        }");
        }

        private static void WriteEnums(StringBuilder code, EquatableArray<ColumnModel> columns)
        {
            foreach (string type in columns.Where(c => c.IsEnum).Select(c => c.ValueType).Distinct())
            {
                code.AppendLine($"            global::ParquetNeo.ColumnTypes.ColumnTypeRegistry.RegisterEnum<{type}>();");
            }
        }

        private static string Bool(bool value) => value ? "true" : "false";

        private static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, quote: true);
    }
}
